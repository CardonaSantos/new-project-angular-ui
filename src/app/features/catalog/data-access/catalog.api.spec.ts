import {HttpTestingController,provideHttpClientTesting} from '@angular/common/http/testing';
import {provideHttpClient} from '@angular/common/http';
import {TestBed} from '@angular/core/testing';
import {CatalogApi,catalogParams} from './catalog.api';

describe('CAT-A HTTP contracts',()=>{
 let api:CatalogApi;let http:HttpTestingController;
 beforeEach(()=>{
  TestBed.configureTestingModule({providers:[provideHttpClient(),provideHttpClientTesting()]});
  api=TestBed.inject(CatalogApi);http=TestBed.inject(HttpTestingController);
 });
 afterEach(()=>http.verify());

 it('omits empty query fields while retaining false and zero',()=>{
  const p=catalogParams({search:'',activo:false,page:2,limit:20,orden:0,unused:null});
  expect(p.keys().sort()).toEqual(['activo','limit','orden','page']);
  expect(p.get('activo')).toBe('false');
 });
 it('covers categories list, tree, options, detail and all writes',()=>{
  api.categories({page:2,activo:false}).subscribe();
  let req=http.expectOne(r=>r.url==='/api/catalog/categories');
  expect(req.request.params.get('activo')).toBe('false');req.flush({data:[],meta:{}});
  api.categoryTree().subscribe();http.expectOne('/api/catalog/categories/tree').flush({data:[],total:0});
  api.categoryOptions({search:'bebida',cursor:'c/1'}).subscribe();
  req=http.expectOne(r=>r.url==='/api/catalog/categories/options');
  expect(req.request.params.get('cursor')).toBe('c/1');req.flush({data:[],meta:{}});
  api.category('c/1').subscribe();http.expectOne('/api/catalog/categories/c%2F1').flush({});
  api.createCategory({nombre:'Bebidas'}).subscribe();
  req=http.expectOne('/api/catalog/categories');expect(req.request.method).toBe('POST');req.flush({});
  api.updateCategory('c1',{nombre:'Café'}).subscribe();
  req=http.expectOne('/api/catalog/categories/c1');expect(req.request.method).toBe('PATCH');req.flush({});
  api.categoryStatus('c1',false,'Descontinuada').subscribe();
  req=http.expectOne('/api/catalog/categories/c1/status');
  expect(req.request.body).toEqual({activo:false,motivo:'Descontinuada'});req.flush({});
  api.categoryMedia('c1',['im1']).subscribe();
  req=http.expectOne('/api/catalog/categories/c1/media');
  expect(req.request.body).toEqual({mediaIds:['im1']});req.flush({});
 });
 it('covers product and variant operations with backend-only allowed fields',()=>{
  api.products({search:'latte',tipo:'PREPARADO'}).subscribe();
  http.expectOne(r=>r.url==='/api/catalog/products').flush({data:[],meta:{}});
  api.productOptions({sucursalId:'b1',search:'latte'}).subscribe();
  http.expectOne(r=>r.url==='/api/catalog/products/options').flush({data:[],meta:{}});
  api.product('p1','b1').subscribe();
  let req=http.expectOne(r=>r.url==='/api/catalog/products/p1');
  expect(req.request.params.get('sucursalId')).toBe('b1');req.flush({});
  api.createProduct({codigo:'LATTE',nombre:'Latte',tipo:'PREPARADO',variantes:[{nombre:'Regular'}]}).subscribe();
  req=http.expectOne('/api/catalog/products');expect(req.request.body.variantes[0].nombre).toBe('Regular');req.flush({});
  api.updateProduct('p1',{visibleEnMenu:true}).subscribe();
  http.expectOne('/api/catalog/products/p1').flush({});
  api.productStatus('p1',false,'Retirado del menú').subscribe();
  http.expectOne('/api/catalog/products/p1/status').flush({});
  api.productMedia('p1',['m1']).subscribe();
  http.expectOne('/api/catalog/products/p1/media').flush({});
  api.createVariant('p1',{nombre:'Grande'}).subscribe();
  http.expectOne('/api/catalog/products/p1/variants').flush({});
  api.productReadiness('p1','b1').subscribe();
  http.expectOne(r=>r.url==='/api/catalog/products/p1/readiness').flush({lista:false,variantes:[]});
  api.variantOptions({sucursalId:'b1'}).subscribe();
  http.expectOne(r=>r.url==='/api/catalog/variants/options').flush({data:[],meta:{}});
  api.variant('v1','b1').subscribe();http.expectOne(r=>r.url==='/api/catalog/variants/v1').flush({});
  api.updateVariant('v1',{nombre:'Mediano'}).subscribe();
  http.expectOne('/api/catalog/variants/v1').flush({});
  api.variantBranch('v1',{sucursalId:'b1',habilitada:false,motivo:'Agotado'}).subscribe();
  req=http.expectOne('/api/catalog/variants/v1/branch');
  expect(req.request.body.habilitada).toBe(false);req.flush({});
  api.variantMedia('v1',['m1']).subscribe();
  http.expectOne('/api/catalog/variants/v1/media').flush({});
 });
 it('covers modifier groups, extras and linking a variant',()=>{
  api.modifierGroups({page:1}).subscribe();
  http.expectOne(r=>r.url==='/api/catalog/modifier-groups').flush({data:[],meta:{}});
  api.modifierGroupOptions({search:'leche'}).subscribe();
  http.expectOne(r=>r.url==='/api/catalog/modifier-groups/options').flush({data:[],meta:{}});
  api.createModifierGroup({nombre:'Leche',minimo:1,maximo:1}).subscribe();
  http.expectOne('/api/catalog/modifier-groups').flush({});
  api.updateModifierGroup('g1',{minimo:0}).subscribe();
  http.expectOne('/api/catalog/modifier-groups/g1').flush({});
  api.modifiers({grupoId:'g1'}).subscribe();
  http.expectOne(r=>r.url==='/api/catalog/modifiers').flush({data:[],meta:{}});
  api.createModifier({grupoId:'g1',nombre:'Avena',incrementoPrecio:'4.00'}).subscribe();
  let req=http.expectOne('/api/catalog/modifiers');
  expect(req.request.body.incrementoPrecio).toBe('4.00');req.flush({});
  api.updateModifier('m1',{requiereComposicion:true}).subscribe();
  http.expectOne('/api/catalog/modifiers/m1').flush({});
  api.attachVariantGroups('v1',[{grupoId:'g1',orden:0,obligatorio:true}]).subscribe();
  req=http.expectOne('/api/catalog/variants/v1/modifier-groups');
  expect(req.request.method).toBe('PUT');req.flush([]);
 });
 it('handles pricing without inventing a PATCH to historical records',()=>{
  const price={entityId:'v1',sucursalId:'b1',importe:'28.00',vigenteDesde:'2026-11-02T12:00:00Z'};
  api.createVariantPrice(price).subscribe();
  let req=http.expectOne('/api/catalog/prices/variants');
  expect(req.request.method).toBe('POST');expect(req.request.body.importe).toBe('28.00');req.flush({});
  api.createModifierPrice({...price,entityId:'m1'}).subscribe();
  http.expectOne('/api/catalog/prices/modifiers').flush({});
  api.variantPriceHistory('v1','b1').subscribe();
  http.expectOne(r=>r.url==='/api/catalog/prices/variants/v1/history').flush([]);
  api.modifierPriceHistory('m1','b1').subscribe();
  http.expectOne(r=>r.url==='/api/catalog/prices/modifiers/m1/history').flush([]);
  api.resolvePrice('v1','b1').subscribe();
  http.expectOne(r=>r.url==='/api/catalog/prices/variants/v1/resolve').flush({});
  api.quote({sucursalId:'b1',varianteId:'v1',modificadorIds:['m1']}).subscribe();
  req=http.expectOne('/api/catalog/prices/quote');
  expect(req.request.body.modificadorIds).toEqual(['m1']);req.flush({});
 });
 it('uses optimistic menu versions for layout and publish, plus reports and preview',()=>{
  api.menus({sucursalId:'b1'}).subscribe();
  http.expectOne(r=>r.url==='/api/catalog/menus').flush({data:[],meta:{}});
  api.createMenu({codigo:'CAFE',nombre:'Carta',sucursalIds:['b1']}).subscribe();
  http.expectOne('/api/catalog/menus').flush({});
  api.menu('menu1').subscribe();http.expectOne('/api/catalog/menus/menu1').flush({});
  api.updateMenu('menu1',{nombre:'Carta renovada'}).subscribe();
  http.expectOne('/api/catalog/menus/menu1').flush({});
  api.replaceMenuLayout('menu1',{expectedVersion:4,sucursalIds:['b1'],
   secciones:[{nombre:'Café',orden:0,items:[{varianteId:'v1',orden:0}]}],horarios:[]}).subscribe();
  let req=http.expectOne('/api/catalog/menus/menu1/layout');
  expect(req.request.method).toBe('PUT');expect(req.request.body.expectedVersion).toBe(4);req.flush({});
  api.publishMenu('menu1',5).subscribe();
  req=http.expectOne('/api/catalog/menus/menu1/publish');
  expect(req.request.body).toEqual({expectedVersion:5});req.flush({});
  api.unpublishMenu('menu1').subscribe();
  req=http.expectOne('/api/catalog/menus/menu1/unpublish');expect(req.request.method).toBe('POST');req.flush({});
  api.branchMenu('b1').subscribe();
  http.expectOne(r=>r.url==='/api/catalog/menu').flush({menus:[]});
  api.summary('b1').subscribe();
  http.expectOne(r=>r.url==='/api/catalog/reports/summary').flush({});
  api.priceCoverage('b1').subscribe();
  http.expectOne(r=>r.url==='/api/catalog/reports/price-coverage').flush({});
 });
});
